def build_key_events(stops_fc):
    coord_by_sid = {}
    coords_by_name = {}
    coords_by_line_name = {}
    for f in stops_fc.get("features", []):
        p = f.get("properties", {})
        c = (f.get("geometry") or {}).get("coordinates")
        if not c or len(c) < 2:
            continue
        pt = [round(float(c[0]), 6), round(float(c[1]), 6)]
        sid = p.get("sid")
        nm = p.get("name", "")
        lid = p.get("lineId", "")
        if sid:
            coord_by_sid[sid] = pt
        if nm:
            coords_by_name.setdefault(nm, []).append(pt)
            if lid:
                coords_by_line_name.setdefault((lid, nm), []).append(pt)

    def lookup_rename_coord(key):
        if ":" in key:
            lid, nm = key.split(":", 1)
            pts = coords_by_line_name.get((lid, nm)) or coords_by_name.get(nm) or []
        else:
            pts = coords_by_name.get(key) or []
        if not pts:
            return None
        return [round(sum(x[0] for x in pts) / len(pts), 6), round(sum(x[1] for x in pts) / len(pts), 6)]

    events = []
    for p in PLAN_APPROVALS:
        events.append({
            "id": p["id"],
            "time": p["time"],
            "date": p["date"],
            "type": "plan",
            "title": p["title"],
            "detail": p["detail"],
            "pauseMs": p["pauseMs"],
        })
    for g in GROUNDBREAKING_EVENTS:
        events.append({
            "id": g["id"],
            "time": g["time"],
            "date": g["date"],
            "type": "build",
            "title": g["title"],
            "detail": g["detail"],
            "pauseMs": g["pauseMs"],
        })
    # 先建后开（暂缓开通）站点启用事件：逐站附精确坐标，触发特写镜头与独立停顿
    for sid, d in sorted(DEFERRED_STATIONS.items(), key=lambda kv: (kv[1]["openTime"], kv[0])):
        if d["openDate"].startswith("暂缓"):
            continue
        dt_lbl = d["openDate"]
        if len(dt_lbl) >= 7 and dt_lbl[4] == "-":
            dt_lbl = dt_lbl[:7].replace("-", "年") + "月"
        ev = {
            "id": f"st-{sid}",
            "time": d["openTime"],
            "date": dt_lbl,
            "type": "station",
            "title": f"{d['lineName']} {d['name']}站开通启用",
            "detail": d["note"],
            "pauseMs": 1400,
            "focusZoom": 13.2,
            "stationName": d["name"],
        }
        if sid in coord_by_sid:
            ev["coord"] = coord_by_sid[sid]
        events.append(ev)
    # 全部历史站名更名事件：逐站附精确坐标，触发特写镜头与独立停顿
    for rkey, entries in STATION_RENAMES.items():
        if not isinstance(entries, list) or len(entries) < 2:
            continue
        coord = lookup_rename_coord(rkey)
        for ri in range(1, len(entries)):
            prev_e = entries[ri - 1]
            cur_e = entries[ri]
            # 跳过仅因新线同站不同名导致的过渡合写项（如 2021-12 东昌路/浦东南路），只对真正改名给特写
            if "/" in cur_e["name"] and cur_e["name"].startswith(prev_e["name"]):
                continue
            dt_str = cur_e["date"]
            if len(dt_str) == 7 and dt_str[4] == "-":
                dt_str = dt_str.replace("-", "年") + "月"
            prefix = "4号线 " if rkey.startswith("l0018:") else ""
            ev = {
                "id": f"rn-{rkey}-{ri}",
                "time": cur_e["time"],
                "date": dt_str,
                "type": "rename",
                "title": f"{prefix}{prev_e['name']} → {cur_e['name']}",
                "detail": cur_e.get("note", "车站更名"),
                "pauseMs": 1400,
                "focusZoom": 13.2,
                "stationName": cur_e["name"],
            }
            if coord:
                ev["coord"] = coord
            events.append(ev)
    for idx, m in enumerate(MILESTONES):
        if m["time"] <= 1990.5:
            continue  # 1990-03 开工已在 GROUNDBREAKING_EVENTS 中，避免重复
        events.append({
            "id": f"ms-{idx}",
            "time": m["time"],
            "date": m["date"],
            "type": "open",
            "title": m["title"],
            "detail": m.get("detail", ""),
            "pauseMs": 0,  # 线路开通已有 1.15s 线末停顿
        })
    type_order = {"plan": 0, "build": 1, "rename": 2, "station": 3, "open": 4}
    events.sort(key=lambda e: (e["time"], type_order.get(e["type"], 9), e["id"]))
    return events


def main():
    lines_fc = json.loads((ROOT / "docs/net/lines.geojson").read_text(encoding="utf-8"))
    stops_fc = json.loads((ROOT / "docs/net/stops.geojson").read_text(encoding="utf-8"))
    segs_by_line = {}
    name_by_line = {}
    for f in lines_fc["features"]:
        p = f["properties"]
        lid = p["lineId"]
        segs_by_line.setdefault(lid, []).append(p["segIndex"])
        name_by_line[lid] = p.get("name", lid)

    missing = [lid for lid in segs_by_line if lid not in LINE_RULES]
    if missing:
        raise SystemExit(f"Missing timeline rules for lines: {missing}")

    out_lines = {}
    for lid, seg_indices in sorted(segs_by_line.items()):
        spec = LINE_RULES[lid]
        max_seg = max(seg_indices)
        min_seg = min(seg_indices)
        covered = set()
        segs_out = []
        for rule in spec["rules"]:
            lo, hi, open_text, t, label, stage = rule[:6]
            build_text = rule[6] if len(rule) >= 8 else ""
            build_time = rule[7] if len(rule) >= 8 else None
            extra = rule[8] if len(rule) >= 9 and isinstance(rule[8], dict) else None
            real_lo = max(lo, min_seg)
            real_hi = min(hi, max_seg)
            if real_lo > real_hi:
                continue
            for si in range(real_lo, real_hi + 1):
                if si in seg_indices:
                    covered.add(si)
            rec = {
                "from": real_lo,
                "to": real_hi,
                "open": open_text,
                "time": t,
                "label": label,
                "stage": stage,
            }
            if build_time is not None:
                rec["build"] = build_text
                rec["buildTime"] = build_time
            ap = APPROVE_MAP.get((lid, lo))
            if ap is not None:
                rec["approve"] = ap[0]
                rec["approveTime"] = ap[1]
            if extra:
                rec.update(extra)
            segs_out.append(rec)
        uncovered = sorted(set(seg_indices) - covered)
        if uncovered:
            raise SystemExit(f"Line {lid} ({name_by_line[lid]}) has uncovered segments: {uncovered}")
        out_lines[lid] = {
            "name": name_by_line[lid],
            "firstOpen": spec["firstOpen"],
            "summary": spec["summary"],
            "segments": segs_out,
        }

    key_events = build_key_events(stops_fc)
    payload = {
        "fmt": "net-timeline@1",
        "range": {"min": 1990.0, "max": 2040.0},
        "milestones": MILESTONES,
        "planApprovals": PLAN_APPROVALS,
        "deferredStations": DEFERRED_STATIONS,
        "keyEvents": key_events,
        "stationRenames": STATION_RENAMES,
        "lines": out_lines,
    }
    raw = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    for dst in (ROOT / "data/timeline.json", ROOT / "docs/net/timeline.json"):
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text(raw, encoding="utf-8")
    print(
        f"Generated timeline.json: {len(out_lines)} lines, {len(MILESTONES)} milestones, "
        f"{len(PLAN_APPROVALS)} plan approvals, {len(DEFERRED_STATIONS)} deferred stations, "
        f"{len(key_events)} key events, {len(STATION_RENAMES)} renamed stations ({len(raw):,} bytes)"
    )


if __name__ == "__main__":
    main()
